const XLSX = require('xlsx');
const fs = require('fs');
const path = require('path');

const outputPath = path.join(process.cwd(), 'test_data.xlsx');

// Sheet 1: Sales Data (Standard)
const salesData = [
  ['ID', 'Date', 'TransactionTime', 'Product', 'Amount', 'Note'],
  [1, new Date('2023-01-01'), new Date('2023-01-01T10:30:00'), 'Widget A', 100.50, 'Standard'],
  [2, new Date('2023-01-02'), new Date('2023-01-02T14:15:30'), 'Widget B', 200.00, 'Discounted'],
  [3, new Date('2023-01-03'), new Date('2023-01-03T09:00:00'), 'Widget A', 100.50, null], // Null note
  [4, new Date('2023-01-04'), new Date('2023-01-04T16:45:00'), 'Widget C', 50.25, 'Refund "Full"'], // Quotes in string
  [5, new Date('2023-01-05'), new Date('2023-01-05T11:20:00'), 'Widget B', 200.00, 'Line\nBreak'], // Newline
];

const wsSales = XLSX.utils.aoa_to_sheet(salesData);

// Sheet 2: Metadata (Messy)
const metaData = [
  ['Report Metadata'], // Merged header
  ['Generated By', 'System V2'],
  [], // Empty row
  ['Key', 'Value', 'Status'],
  ['Version', '1.2.3', 'Active'],
  ['Region', 'APAC', 'Active'],
];

const wsMeta = XLSX.utils.aoa_to_sheet(metaData);

// Add Merge: A1:C1
if(!wsMeta['!merges']) wsMeta['!merges'] = [];
wsMeta['!merges'].push({ s: { r: 0, c: 0 }, e: { r: 0, c: 2 } }); 

const workbook = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(workbook, wsSales, 'SalesData');
XLSX.utils.book_append_sheet(workbook, wsMeta, 'Metadata');

XLSX.writeFile(workbook, outputPath);

console.log(`Generated test Excel file at: ${outputPath}`);
console.log('Use this file to test ingestion logic.');
