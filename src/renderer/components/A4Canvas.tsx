// 数据表格组件
interface A4DataTableProps {
  data: Array<Record<string, any>>
  maxRows?: number
  className?: string
}

export function A4DataTable({
  data,
  maxRows = 20,
  className = '',
}: A4DataTableProps) {
  if (!data || data.length === 0) {
    return (
      <div className={`text-center py-8 text-gray-500 ${className}`}>
        暂无数据
      </div>
    )
  }

  const displayData = data.slice(0, maxRows)
  const columns = Object.keys(data[0])
  const hasMore = data.length > maxRows

  return (
    <div className={className}>
      <div className="overflow-x-auto">
        <table className="w-full text-sm border-collapse">
          <thead>
            <tr className="bg-gray-50">
              {columns.map(column => (
                <th
                  key={column}
                  className="px-3 py-2 text-left font-medium text-gray-700 border-b border-gray-200"
                >
                  {column}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {displayData.map((row, index) => (
              <tr key={index} className="hover:bg-gray-50">
                {columns.map(column => (
                  <td
                    key={column}
                    className="px-3 py-2 text-gray-900 border-b border-gray-100"
                  >
                    {row[column]}
                  </td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      </div>

      {hasMore && (
        <div className="mt-3 text-center text-sm text-gray-500">
          显示前 {maxRows} 条，共 {data.length} 条数据
        </div>
      )}
    </div>
  )
}

// 预设的 A4 报表布局
interface A4ReportLayoutProps {
  title: string
  subtitle?: string
  summary?: string
  insights?: string[]
  chartType?: 'bar' | 'line' | 'pie' | 'area' | 'table' | 'scatter' | 'kpi'
  chartTitle?: string
  tableData?: Array<Record<string, any>>
  vizConfig?: {
    x_axis?: string | null
    y_axis?: string | string[] | null
    series_name?: string
  }
  logo?: string
  className?: string
}

export function A4ReportLayout({
  title,
  subtitle,
  summary,
  insights,
  chartType = 'bar',
  chartTitle,
  tableData,
  vizConfig,
  logo,
  className = '',
}: A4ReportLayoutProps) {
  return (
    <A4Canvas className={className}>
      <A4Header title={title} subtitle={subtitle} logo={logo} />

      {summary && (
        <A4Section title="数据摘要">
          <A4Summary content={summary} insights={insights} />
        </A4Section>
      )}

      <A4Section title="数据可视化">
        <A4Chart
          type={chartType}
          title={chartTitle}
          data={tableData}
          config={vizConfig}
        />
      </A4Section>

      {tableData && tableData.length > 0 && (
        <A4Section title="数据明细">
          <A4DataTable data={tableData} />
        </A4Section>
      )}

      <A4Footer />
    </A4Canvas>
  )
}
