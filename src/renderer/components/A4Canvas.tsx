// 图表组件
interface A4ChartProps {
  type?: 'bar' | 'line' | 'pie' | 'area' | 'table' | 'scatter' | 'kpi' // Added 'table' to be safe, though handled in parent
  title?: string
  data?: Array<Record<string, any>>
  config?: {
    x_axis?: string | null
    y_axis?: string | string[] | null
    series_name?: string
  }
  className?: string
  style?: React.CSSProperties
}

export function A4Chart({
  type = 'bar',
  title = '数据图表',
  data = [],
  config,
  className = '',
  style,
}: A4ChartProps) {
  const chartRef = useRef<any>(null)
  const containerRef = useRef<HTMLDivElement | null>(null)

  const resizeChart = useCallback(() => {
    const instance = chartRef.current?.getEchartsInstance?.()
    if (instance) {
      instance.resize()
    }
  }, [])

  useEffect(() => {
    resizeChart()
  }, [resizeChart, data, type, config])

  useEffect(() => {
    const handler = () => requestAnimationFrame(resizeChart)
    window.addEventListener('resize', handler)
    window.addEventListener('dashboard:layout-changed', handler)
    return () => {
      window.removeEventListener('resize', handler)
      window.removeEventListener('dashboard:layout-changed', handler)
    }
  }, [resizeChart])

  useEffect(() => {
    if (!containerRef.current) return
    const observer = new ResizeObserver(() => resizeChart())
    observer.observe(containerRef.current)
    return () => observer.disconnect()
  }, [resizeChart])

  // Safety check: If no config, or missing axes (unless it's a special type, but generally we need axes for charts), return null
  // We explicitly check for x_axis and y_axis. If they are null/undefined, we can't render an EChart.
  if (
    !data ||
    data.length === 0 ||
    !config ||
    !config.x_axis ||
    !config.y_axis ||
    type === 'table' ||
    type === 'kpi'
  ) {
    return null
  }

  const { x_axis, y_axis, series_name } = config
  const yAxes = Array.isArray(y_axis) ? y_axis : [y_axis]

  const getOption = () => {
    // Double check for TS safety, though covered by the if above
    if (!x_axis || !y_axis) return {}

    const xData = data.map(item => item[x_axis])

    const baseSeries =
      type === 'scatter'
        ? yAxes.map(key => ({
            name: series_name || key,
            type: 'scatter',
            data: data.map(item => [item[x_axis], item[key]]),
            emphasis: { focus: 'series' },
          }))
        : yAxes.map(key => ({
            name: series_name || key,
            type: type === 'area' ? 'line' : type,
            data: data.map(item => item[key]),
            areaStyle: type === 'area' ? {} : undefined,
            itemStyle: {
              color: '#4F46E5', // Indigo-600
            },
          }))

    const baseOption = {
      tooltip: {
        trigger: type === 'pie' ? 'item' : 'axis',
      },
      grid: {
        left: '3%',
        right: '4%',
        bottom: '3%',
        containLabel: true,
      },
      xAxis:
        type === 'scatter'
          ? { type: 'value' }
          : {
              type: 'category',
              data: xData,
              axisLabel: { interval: 0, rotate: 30 }, // Avoid overlap
            },
      yAxis: {
        type: 'value',
      },
      series: baseSeries,
    }

    if (type === 'pie') {
      return {
        tooltip: { trigger: 'item' },
        series: [
          {
            name: series_name || yAxes[0],
            type: 'pie',
            radius: '50%',
            data: data.map(item => ({
              value: item[yAxes[0]],
              name: item[x_axis],
            })),
            emphasis: {
              itemStyle: {
                shadowBlur: 10,
                shadowOffsetX: 0,
                shadowColor: 'rgba(0, 0, 0, 0.5)',
              },
            },
          },
        ],
      }
    }

    return baseOption
  }

  const option = useMemo(() => getOption(), [data, type, config])

  return (
    <div
      className={className}
      ref={containerRef}
      style={{ height: '100%', width: '100%', ...style }}
    >
      <ReactECharts
        key={type}
        option={option}
        style={{ height: '100%', width: '100%', ...style }}
        opts={{ renderer: 'canvas' }}
        ref={chartRef}
        onChartReady={resizeChart}
        notMerge
        autoResize
      />
    </div>
  )
}

